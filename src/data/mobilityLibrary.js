// Builds the {name, muscle} shape MuscleBodyOutline/getMuscleDisplay already understand — reused
// unmodified rather than teaching anatomy about a second data shape.
export function mobilityAnatomyExercise(movement) {
  const region = movement?.primaryRegions?.[0] || movement?.bodyRegion?.[0];
  return { name: movement?.name, muscle: REGION_TO_BROAD_MUSCLE[region] || "Full body" };
}

export function mobilityById(id) {
  return MOBILITY_LIBRARY.find((m) => m.id === id) || null;
}

